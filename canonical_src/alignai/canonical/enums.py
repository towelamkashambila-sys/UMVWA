    DRAFT="DRAFT"; ACTIVE="ACTIVE"; ACKNOWLEDGED="ACKNOWLEDGED"; STARTED="STARTED"; WAITING="WAITING"; BLOCKED="BLOCKED"; ON_HOLD="ON_HOLD"; COMPLETED="COMPLETED"; CANCELLED="CANCELLED"; SUPERSEDED="SUPERSEDED"
